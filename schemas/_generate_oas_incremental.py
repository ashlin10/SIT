"""Generate schemas/oas_schemas/SCHEMA_INCREMENTAL_UPDATES.md.

Walks the version-ordered FMC OAS documents in ``oas_schemas/`` and, for every
release transition, lists the component schemas added, removed, and (for schemas
present in both releases) the properties added/removed.

Usage:
    python schemas/_generate_oas_incremental.py
"""
from __future__ import annotations

import json
import os
from typing import Dict, List, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
OAS_DIR = os.path.join(HERE, "oas_schemas")
OUT = os.path.join(OAS_DIR, "SCHEMA_INCREMENTAL_UPDATES.md")

# version_label, filename (ordered oldest -> newest) — mirrors
# web_app/pre_push_validation/oas_schema_loader.OAS_VERSIONS
VERSIONS: List[Tuple[str, str]] = [
    ("7.0", "fmc_7_0.json"),
    ("7.1", "fmc_oas3_7_1.json"),
    ("7.2", "fmc_oas3_7_2.json"),
    ("7.3", "fmc_oas3_7_3.json"),
    ("7.4", "fmc_oas3_7_4.json"),
    ("7.6", "fmc_oas3_7_6.json"),
    ("7.7", "fmc_oas3_7_7.json"),
    ("10.0", "fmc_oas3_10_0.json"),
    ("10.1", "fmc_oas3_10_1.json"),
    ("10.5", "fmc_oas3_10_5.json"),
]

# Cap on how many field changes to print per schema (keeps the doc readable).
MAX_FIELDS_PER_MODEL = 40


def load_schemas(fname: str) -> Dict[str, set]:
    """Return {schema_name: set(property_names)} for an OAS document."""
    path = os.path.join(OAS_DIR, fname)
    with open(path, "r") as f:
        doc = json.load(f)
    schemas = ((doc.get("components") or {}).get("schemas")) or {}
    if not schemas:
        # Swagger 2.0 fallback (FMC 7.0 document uses top-level definitions).
        schemas = doc.get("definitions") or {}
    out: Dict[str, set] = {}
    for name, body in schemas.items():
        props = set()
        if isinstance(body, dict):
            props |= set((body.get("properties") or {}).keys())
            for part in (body.get("allOf") or []):
                if isinstance(part, dict):
                    props |= set((part.get("properties") or {}).keys())
        out[name] = props
    return out


HEADER = """# FMC OAS (OpenAPI) Schema Incremental Updates (7.0 → 10.5)

Auto-generated from the per-version `fmc_oas3_<version>.json` OpenAPI documents in
this folder. For every release transition it lists the **component schemas added**,
**schemas removed**, and for schemas present in both releases, the **properties
added/removed**.

> Generated by `schemas/_generate_oas_incremental.py`. Do not edit by hand;
> re-run the generator to refresh.

## How the OAS schemas are organized

- Each file in this folder is a full **FMC OpenAPI 3 specification** for one FMC
  release (e.g. `fmc_oas3_7_2.json`). The 7.0 document is named `fmc_7_0.json`.
- The validation system only consumes the **`components.schemas`** section of each
  document. Every entry there is a JSON-Schema object describing one FMC REST API
  request/response model (e.g. `FTDPhysicalInterface`, `HostObject`,
  `SecurityZoneObject`). Nested objects are referenced with `$ref`
  (`#/components/schemas/<Name>`); arrays use `items.$ref`.
- The OAS documents are **versioned by FMC release**. There are no 6.x, 7.4.1, or
  7.5 OAS documents; the validator resolves a device's FMC version to the closest
  available document that is **&le;** the requested version
  (`resolve_oas_version` in `web_app/pre_push_validation/oas_schema_loader.py`).

## How the OAS schemas are updated

- When a new FMC release is supported, drop its OpenAPI 3 JSON document into this
  folder using the `fmc_oas3_<major>_<minor>.json` naming convention.
- Add the new `(version_label, filename)` pair to **both**:
  - `OAS_VERSIONS` in `web_app/pre_push_validation/oas_schema_loader.py`
  - `VERSIONS` in `schemas/_generate_oas_incremental.py`
- Re-run `python schemas/_generate_oas_incremental.py` to refresh this changelog.

## How the OAS schemas are used by validation

- `oas_schema_loader.py` resolves the FMC version → closest OAS document, loads
  its `components.schemas`, and caches the parsed result.
- `oas_schema_validator.py` builds an `OasSchemaIndex` (schema → allowed property
  set, with `$ref` resolution for recursion) and walks the loaded YAML config:
  - Interface sections map to known OAS schema names via
    `SECTION_TO_OAS_SCHEMA` (e.g. `physical_interfaces → FTDPhysicalInterface`).
  - Routing/objects are discovered generically by resolving each typed object's
    `type` discriminator to an OAS component schema.
  - Any field not present in the resolved schema's property set is flagged as
    **unsupported/deprecated** for the target FMC version and offered as an
    auto-fixable removal.
- This replaces the previous `ftl_schemas` based field validation, which was not
  accurate. Model/interface capability checks (speed, supported interface types,
  EtherChannel ranges, VRF support) continue to use `schemas/model_schemas/`.

"""


def main() -> None:
    lines: List[str] = [HEADER]
    base_label, base_file = VERSIONS[0]
    base = load_schemas(base_file)
    lines.append(f"## Baseline — FMC {base_label} (`{base_file}`)\n")
    lines.append(f"- **Total component schemas:** {len(base)}\n")
    lines.append("\n---\n")

    prev = base
    prev_label = base_label
    for label, fname in VERSIONS[1:]:
        cur = load_schemas(fname)
        prev_names = set(prev.keys())
        cur_names = set(cur.keys())
        added = sorted(cur_names - prev_names)
        removed = sorted(prev_names - cur_names)

        gained: List[Tuple[str, List[str]]] = []
        lost: List[Tuple[str, List[str]]] = []
        for name in sorted(prev_names & cur_names):
            add_f = sorted(cur[name] - prev[name])
            rem_f = sorted(prev[name] - cur[name])
            if add_f or rem_f:
                gained.append((name, add_f)) if add_f else None
                lost.append((name, rem_f)) if rem_f else None

        lines.append(f"## FMC {label} (`{fname}`) — changes vs {prev_label}\n")
        lines.append(
            f"- Schema count: {len(prev_names)} → {len(cur_names)}  "
            f"(**+{len(added)}** added, **-{len(removed)}** removed)\n\n"
        )

        if added:
            lines.append(f"### Schemas added ({len(added)})\n")
            for n in added:
                lines.append(f"- `{n}`")
            lines.append("")
        if removed:
            lines.append(f"### Schemas removed ({len(removed)})\n")
            for n in removed:
                lines.append(f"- `{n}`")
            lines.append("")

        if gained or lost:
            lines.append(
                f"### Field-level changes ({len(gained)} schemas gained properties, "
                f"{len(lost)} schemas lost properties)\n"
            )
            change_map: Dict[str, Tuple[List[str], List[str]]] = {}
            for name, add_f in gained:
                change_map.setdefault(name, ([], []))
                change_map[name] = (add_f, change_map[name][1])
            for name, rem_f in lost:
                change_map.setdefault(name, ([], []))
                change_map[name] = (change_map[name][0], rem_f)
            for name in sorted(change_map):
                add_f, rem_f = change_map[name]
                parts = []
                if add_f:
                    shown = add_f[:MAX_FIELDS_PER_MODEL]
                    suffix = "" if len(add_f) <= MAX_FIELDS_PER_MODEL else f" … (+{len(add_f) - MAX_FIELDS_PER_MODEL} more)"
                    parts.append("added: " + ", ".join(f"`{x}`" for x in shown) + suffix)
                if rem_f:
                    shown = rem_f[:MAX_FIELDS_PER_MODEL]
                    suffix = "" if len(rem_f) <= MAX_FIELDS_PER_MODEL else f" … (+{len(rem_f) - MAX_FIELDS_PER_MODEL} more)"
                    parts.append("removed: " + ", ".join(f"`{x}`" for x in shown) + suffix)
                lines.append(f"- **{name}** — " + "; ".join(parts))
            lines.append("")

        lines.append("---\n")
        prev = cur
        prev_label = label

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
